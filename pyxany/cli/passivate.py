"""``pyxany passivate`` -- add hydrogen / pseudo-hydrogen terminators to a cluster."""

from __future__ import annotations

import os
from pathlib import Path

import yaml

from ..config import ConfigError
from ..io.xyz import read_xyz, write_xyz
from ..parallel import is_root, mpi_print
from ..passivation import format_report, passivate
from ..timing import REGISTRY, timer
from . import EXIT_OK


def execute(args) -> int:
    REGISTRY.reset()
    with timer("total"):
        code = _passivate(args)
    # Coordination detection is an O(N^2) neighbor search, so on a 200-atom
    # cluster it is worth knowing where the time went.
    if getattr(args, "timing", None):
        REGISTRY.report(printer=mpi_print, min_seconds=0.0)
    return code


def _passivate(args) -> int:
    with timer("read structure"):
        molecule = read_xyz(args.structure)
        reference = read_xyz(args.reference) if args.reference else None

    with timer("passivate"):
        result = passivate(
            molecule, scheme=args.scheme, tolerance=args.tolerance,
            coordination=args.coordination, reference=reference,
            role_overrides=_role_overrides(getattr(args, "role", None)),
            bond_scale=args.bond_scale,
        )

    if not args.quiet:
        mpi_print(format_report(result, args.scheme))

    out_path = Path(args.output or _default_output(args.structure))
    comment = (f"{molecule.name} passivated ({args.scheme}): "
               f"{result.n_added} terminators, "
               f"{result.molecule.n_electrons:g} electrons")
    with timer("write"):
        if is_root():
            write_xyz(out_path, result.molecule, comment)
    if not args.quiet:
        mpi_print(f"  structure written to {out_path}")

    if args.emit_yaml:
        if is_root():
            _write_yaml(args, result, out_path)
        if not args.quiet:
            mpi_print(f"  input template written to {args.emit_yaml}")
    return EXIT_OK


def _role_overrides(items) -> dict | None:
    """``--role Mn=cation`` (repeatable): the overrides the role check asks for,
    which no CLI option could set (MnO, FeO, TiC always failed; ADR 0012 P0)."""
    if not items:
        return None
    out = {}
    for item in items:
        element, _, role = item.partition("=")
        role = role.strip().lower()
        if not element.strip() or role not in ("anion", "cation"):
            raise ConfigError(f"--role {item!r}: expected ELEMENT=anion or ELEMENT=cation")
        out[element.strip()] = role
    return out


def _default_output(structure: str) -> str:
    p = Path(structure)
    return str(p.with_name(p.stem + "_passivated" + p.suffix))


def _write_yaml(args, result, structure_path: Path) -> None:
    name = Path(args.emit_yaml).stem
    doc = {
        "molecule": {
            "name": name,
            # relative to the YAML file, which is how the structure is resolved
            # (the bare file name failed whenever the two were in different
            # directories)
            "structure": os.path.relpath(structure_path.resolve(),
                                         Path(args.emit_yaml).resolve().parent),
            "charge": 0,
            "mult": 1,
            "units": "angstrom",
        },
        "passivation": {"species": result.species_yaml()},
        "basis": {"set": "dz"},
        "grid": {"n_r": 30, "n_a": 12, "poisson_l_max": "auto"},
        "scf": {"max_iter": 150, "e_tol": 1.0e-6, "d_tol": 1.0e-5, "alpha": 0.7},
        "forces": {"enabled": True, "method": "analytic"},
        "optimize": {"enabled": False, "freeze": "core", "f_max": 1.0e-3},
        "output": {"dir": "./results", "prefix": name},
    }
    if args.scheme == "hydrogen":
        doc.pop("passivation")
    Path(args.emit_yaml).write_text(
        "# Generated by 'pyxany passivate'.\n"
        "# 'optimize.freeze: core' relaxes only the terminators, which is how the\n"
        "# X-H* distances are meant to be determined -- the values in the .xyz are\n"
        "# only a covalent-radius initial guess.\n"
        + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)
    )
